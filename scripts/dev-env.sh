#!/usr/bin/env bash
# Share fixed tooling and dependency bytes; keep mutable Cargo state local.
set -euo pipefail
cd "$(dirname "$0")/.."
# print-dev-env emits Bash 4+ syntax. macOS launchd and clean runners can
# enter through the system's Bash 3, so use the pinned shell before sourcing it.
if (( BASH_VERSINFO[0] < 4 )); then
    exec nix develop . --no-update-lock-file --command bash "$PWD/scripts/dev-env.sh" "$@"
fi
agent_root=$PWD
agent_build_root=$(git config --path --get bex.buildRoot || true)
if [[ -n $agent_build_root ]]; then
    # Keep conventional target paths for Cargo, Xcode and generated bindings.
    # Never create the root: an unplugged build volume must fail visibly.
    if [[ $agent_build_root != /* || ! -d $agent_build_root ]]; then
        printf 'Build storage is unavailable: %s\n' "$agent_build_root" >&2
        exit 1
    fi
    if [[ ! -e $agent_root/target && ! -L $agent_root/target ]]; then
        agent_build_key=$(printf '%s\n' "$agent_root" | git hash-object --stdin)
        mkdir -p "$agent_build_root/$agent_build_key"
        # Do not follow a directory link created by a concurrent invocation.
        ln -sn "$agent_build_root/$agent_build_key" "$agent_root/target" ||
            [[ -L $agent_root/target && $(readlink "$agent_root/target") == "$agent_build_root/$agent_build_key" ]]
    fi
fi
# Cargo tags only target directories it creates; this wrapper creates them first.
mkdir -p "$agent_root/target"
if [[ ! -e $agent_root/target/CACHEDIR.TAG && ! -L $agent_root/target/CACHEDIR.TAG ]]; then
    (set -o noclobber; printf '%s\n' 'Signature: 8a477f597d28d172789f06886806bc55' > "$agent_root/target/CACHEDIR.TAG") ||
        [[ -f $agent_root/target/CACHEDIR.TAG && ! -L $agent_root/target/CACHEDIR.TAG ]]
fi
agent_seed_cargo=${CARGO_HOME:-$HOME/.cargo}
export XDG_CACHE_HOME="$agent_root/target/tool-cache"
agent_env_key=$({ git hash-object flake.nix flake.lock tools/github-release-binary.nix tools/cccc/package.nix tools/kache/package.nix tools/node-runtime/package.nix; uname -sm; } | git hash-object --stdin)
agent_env_dir="$(git rev-parse --git-common-dir)/agent-dev-env/$agent_env_key"
mkdir -p "$agent_env_dir"
if [[ ! -f $agent_env_dir/env.sh ]]; then
    agent_pending_env=$(mktemp -d "$agent_env_dir/bootstrap.XXXXXX")
    trap 'rm -rf "$agent_pending_env"' EXIT
    nix --option eval-cache false print-dev-env . --no-update-lock-file \
        --profile "$agent_pending_env/profile" > "$agent_pending_env/env.sh"
    # Publish once, without a shared reader lock. Keep the winning GC root.
    if ! ln "$agent_pending_env/env.sh" "$agent_env_dir/env.sh" 2>/dev/null; then
        [[ -f $agent_env_dir/env.sh ]]
        rm -rf "$agent_pending_env"
    fi
    trap - EXIT
fi
agent_original_tmpdir=${TMPDIR:-/tmp}
agent_original_build_top=${NIX_BUILD_TOP-}
# Generated by nix print-dev-env from the current pinned flake.
# shellcheck disable=SC1091
source "$agent_env_dir/env.sh"
# print-dev-env creates a fresh shell directory; these commands need only the
# environment. Restore the caller's temporary directory and remove the empty one.
rmdir "$NIX_BUILD_TOP"
export TMPDIR="$agent_original_tmpdir" TMP="$agent_original_tmpdir"
export TEMP="$agent_original_tmpdir" TEMPDIR="$agent_original_tmpdir"
if [[ -n $agent_original_build_top ]]; then
    export NIX_BUILD_TOP="$agent_original_build_top"
else
    unset NIX_BUILD_TOP
fi
export CARGO_TARGET_DIR="$agent_root/target"
export CARGO_HOME="$agent_root/target/cargo-home"
agent_seed_key=$(git hash-object Cargo.lock tools/agent-peer/Cargo.lock | git hash-object --stdin)
if [[ ! -f $CARGO_HOME/.seeded || $(< "$CARGO_HOME/.seeded") != "$agent_seed_key" ]]; then
    mkdir -p "$CARGO_HOME/registry" "$CARGO_HOME/git/db" "$CARGO_HOME/git/checkouts"
    agent_copy_cache() {
        if [[ $(uname -s) == Darwin ]]; then
            /bin/cp -cpR "$@" || /bin/cp -pR "$@"
        else
            cp --reflink=auto -pR "$@"
        fi
    }
    # Clone only locked sources and archives. APFS/reflinks share their bytes
    # without sharing Cargo's locks, index updates or automatic cache deletion.
    agent_packages=()
    while IFS= read -r agent_package; do agent_packages+=("$agent_package"); done < <(
        awk '/^name = / { name = $3; gsub(/"/, "", name) }
             /^version = / { version = $3; gsub(/"/, "", version) }
             /^source = "registry\+https:\/\/github.com\/rust-lang\/crates.io-index"/ { print name "-" version }' \
            Cargo.lock tools/agent-peer/Cargo.lock | sort -u
    )
    if [[ $agent_seed_cargo != "$CARGO_HOME" ]]; then
        for agent_index in "$agent_seed_cargo/registry/index"/index.crates.io-*; do
            [[ -d $agent_index ]] || continue
            agent_registry=${agent_index##*/}
            mkdir -p "$CARGO_HOME/registry/index"
            if [[ ! -d $CARGO_HOME/registry/index/$agent_registry ]]; then
                agent_copy_cache "$agent_index" "$CARGO_HOME/registry/index/"
            fi
            for agent_kind in src cache; do
                agent_suffix=
                [[ $agent_kind == cache ]] && agent_suffix=.crate
                agent_destination="$CARGO_HOME/registry/$agent_kind/$agent_registry"
                mkdir -p "$agent_destination"
                agent_sources=()
                for agent_package in "${agent_packages[@]}"; do
                    agent_cached="$agent_seed_cargo/registry/$agent_kind/$agent_registry/$agent_package$agent_suffix"
                    if [[ -e $agent_cached && ! -e $agent_destination/$agent_package$agent_suffix ]]; then
                        agent_sources+=("$agent_cached")
                    fi
                done
                if (( ${#agent_sources[@]} )); then
                    agent_copy_cache "${agent_sources[@]}" "$agent_destination/"
                fi
            done
        done
        while read -r agent_repo agent_revision; do
            for agent_cached in "$agent_seed_cargo/git/db/$agent_repo"-*; do
                if [[ -d $agent_cached && ! -e $CARGO_HOME/git/db/${agent_cached##*/} ]]; then
                    agent_copy_cache "$agent_cached" "$CARGO_HOME/git/db/"
                fi
            done
            for agent_checkout in "$agent_seed_cargo/git/checkouts/$agent_repo"-*; do
                agent_cached="$agent_checkout/$agent_revision"
                agent_destination="$CARGO_HOME/git/checkouts/${agent_checkout##*/}"
                if [[ -d $agent_cached && ! -e $agent_destination/$agent_revision ]]; then
                    mkdir -p "$agent_destination"
                    agent_copy_cache "$agent_cached" "$agent_destination/"
                fi
            done
        done < <(awk '/^source = "git\+/ {
            source = $3; gsub(/"/, "", source); split(source, parts, "#")
            revision = substr(parts[2], 1, 7)
            sub(/[?#].*/, "", source); sub(/.*\//, "", source); sub(/\.git$/, "", source)
            print source, revision
        }' Cargo.lock tools/agent-peer/Cargo.lock | sort -u)
    fi
    printf '%s\n' "$agent_seed_key" > "$CARGO_HOME/.seeded"
fi
exec "$@"
